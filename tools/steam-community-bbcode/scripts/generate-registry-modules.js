import {readFile, writeFile} from 'node:fs/promises';
import {parseArgs} from 'node:util';
import {readSpecificationDocuments, validateSpecification} from './validate-specification.js';

const {values} = parseArgs({options: {check: {type: 'boolean', default: false}}});
const registry = validateSpecification(await readSpecificationDocuments());
// These are data projections of validated collections, not a schema compiler or
// a second handwritten catalogue. JSON.stringify owns literal escaping.
const source = [
  '// SPDX-License-Identifier: AGPL-3.0-only',
  '// Generated by scripts/generate-registry-modules.js from spec/*.json.',
  '// Edit the registry, then regenerate. Do not edit this projection by hand.',
  `export const steamDialectProfileIds = Object.freeze(/** @type {const} */ (${JSON.stringify(registry.profiles.profiles.map(profile => profile.id))}));`,
  `export const steamConstructIds = Object.freeze(/** @type {const} */ (${JSON.stringify(registry.constructs.constructs.map(construct => construct.id))}));`,
  `export const defaultSteamDialectProfile = ${JSON.stringify(registry.profiles.defaultProfile)};`,
  "/** @typedef {(typeof steamDialectProfileIds)[number]} SteamDialectProfileId */",
  "/** @typedef {(typeof steamConstructIds)[number]} ConstructId */",
  '',
].join('\n');
const definitions = [
  '// SPDX-License-Identifier: AGPL-3.0-only',
  '// Generated by scripts/generate-registry-modules.js from spec/*.json.',
  '// Edit the registry, then regenerate. Do not edit this projection by hand.',
  `export const steamRegistryVersion = ${JSON.stringify(registry.constructs.registryVersion)};`,
  `export const steamConstructDefinitions = Object.freeze(/** @type {const} */ (${JSON.stringify(registry.constructs.constructs, null, 2)}));`,
  '/** @typedef {(typeof steamConstructDefinitions)[number]} SteamConstructDefinition */',
  '',
].join('\n');
for (const [name, content] of [['registry-identifiers.js', source], ['construct-registry.js', definitions]]) {
  if (!name || content === undefined) throw new Error('Missing generated registry output.');
  const target = new URL(`../src/steam/${name}`, import.meta.url);
  if (values.check) {
    if (await readFile(target, 'utf8') !== content) throw new Error(`${name} is stale. Run npm run spec:generate.`);
  } else {
    await writeFile(target, content);
  }
}
if (values.check) console.log('Registry module projections match validated source data.');
